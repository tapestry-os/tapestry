# ── Recording format ─────────────────────────────────────────────────────────

def test_wm_entry_flags_are_coerced_to_real_booleans():
    entries = choreo_sim.parse_wm_entries(
        '[{"id":0,"x":1.0,"y":2.0,"is_active":true,"is_stale":false,'
        '"is_self":true,"achieved":true}]')
    e = entries[0]
    assert (e["is_active"], e["is_stale"], e["is_self"], e["achieved"]) \
        == (True, False, True, True)


def test_an_absent_achieved_key_defaults_to_not_achieved():
    entries = choreo_sim.parse_wm_entries(
        '[{"id":0,"x":0,"y":0,"is_active":true,"is_stale":false,'
        '"is_self":true}]')
    assert entries[0]["achieved"] is False


def test_the_committed_fixture_is_reproducible():
    """helpers.py regenerates data/ — if this fails the fixture and the
    generator have parted ways, and the replay test above is checking a
    recording nothing produces any more."""
    assert rows_of(FIXTURE)[1:] == [
        [str(f) for f in row] for row in record_reference_run(SCRIPT_TOML)]


# ── CLI argument handling ────────────────────────────────────────────────────

@pytest.mark.parametrize("args,message", [
    (["--replay", "--script", "S"], "--replay requires --telemetry"),
    (["--simulate", "--script", "S"], "--simulate requires --elements"),
    (["--simulate", "--script", "S", "--elements", "2", "--out", "x.png"],
     "--out has no effect without --plot"),
    (["--script", "S"], "one of the arguments"),
])
def test_incoherent_argument_combinations_are_refused(args, message):
    r = run_cli(*[a if a != "S" else str(SCRIPT_TOML) for a in args])
    assert r.returncode != 0
    assert message in r.stderr


def test_the_two_modes_are_mutually_exclusive():
    r = run_cli("--replay", "--simulate", "--script", SCRIPT_TOML)
    assert r.returncode != 0
    assert "not allowed with" in r.stderr


def test_plotting_stays_a_lazy_import():
    """Compiling or replaying a script must stay dependency-free (see
    choreoc.py: "standard library only... nothing to install"), so
    matplotlib may only be imported inside plot_records()."""
    import ast
    tree = ast.parse((REPO_ROOT / "sdk/tools/choreo_sim.py").read_text())
    module_level = [n for n in tree.body if isinstance(n, (ast.Import,
                                                          ast.ImportFrom))]
    names = {a.name.split(".")[0] for n in module_level
             if isinstance(n, ast.Import) for a in n.names}
    names |= {(n.module or "").split(".")[0] for n in module_level
              if isinstance(n, ast.ImportFrom)}
    assert "matplotlib" not in names
